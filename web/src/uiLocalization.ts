const nodeSources = new WeakMap<Text, string>()
const nodeLastApplied = new WeakMap<Text, string>()
const attributeSources = new WeakMap<Element, Map<string, { source: string; last: string }>>()

function preserveOuterWhitespace(original: string, translated: string): string {
  const leading = original.match(/^\s*/)?.[0] ?? ''
  const trailing = original.match(/\s*$/)?.[0] ?? ''
  return `${leading}${translated}${trailing}`
}

