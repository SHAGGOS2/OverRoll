export function translateUiText(locale: SupportedLocale, input: string): string {
  if (!input || locale === 'es-mx' || locale === 'es-es') return input
  const trimmed = input.trim()
  if (!trimmed) return input
  const exact = maps[locale]?.[trimmed]
  const translated = exact ?? translateDynamic(locale, trimmed)
  return translated == null ? input : preserveOuterWhitespace(input, translated)
}

function shouldSkipElement(element: Element | null): boolean {
  if (!element) return false
  const tag = element.tagName.toLowerCase()
  return tag === 'script' || tag === 'style' || tag === 'textarea' || element.closest('[data-no-auto-i18n="true"]') !== null
}

function localizeTextNode(node: Text, locale: SupportedLocale) {
  if (shouldSkipElement(node.parentElement)) return
  const current = node.nodeValue ?? ''
  const previousLast = nodeLastApplied.get(node)
  if (!nodeSources.has(node) || (previousLast !== undefined && current !== previousLast)) nodeSources.set(node, current)
  const source = nodeSources.get(node) ?? current
  const translated = translateUiText(locale, source)
  if (current !== translated) node.nodeValue = translated
  nodeLastApplied.set(node, translated)
}

const translatedAttributes = ['title', 'aria-label', 'placeholder'] as const
function localizeElementAttributes(element: Element, locale: SupportedLocale) {
  if (shouldSkipElement(element)) return
  let stored = attributeSources.get(element)
  if (!stored) {
    stored = new Map()
    attributeSources.set(element, stored)
  }
  translatedAttributes.forEach((attribute) => {
    const current = element.getAttribute(attribute)
    if (current == null) return
    const record = stored!.get(attribute)
    if (!record || current !== record.last) stored!.set(attribute, { source: current, last: current })
    const active = stored!.get(attribute)!
    const translated = translateUiText(locale, active.source)
    if (translated !== current) element.setAttribute(attribute, translated)
    active.last = translated
  })
}

function localizeTree(root: Node, locale: SupportedLocale) {
  if (root.nodeType === Node.TEXT_NODE) {
    localizeTextNode(root as Text, locale)
    return
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return
  if (root.nodeType === Node.ELEMENT_NODE) localizeElementAttributes(root as Element, locale)
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT)
  let node = walker.nextNode()
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) localizeTextNode(node as Text, locale)
    else localizeElementAttributes(node as Element, locale)
    node = walker.nextNode()
  }
}

export function installUiLocalization(locale: SupportedLocale): () => void {
  if (typeof document === 'undefined') return () => undefined
  localizeTree(document.body, locale)
  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === 'characterData') localizeTextNode(mutation.target as Text, locale)
      mutation.addedNodes.forEach((node) => localizeTree(node, locale))
      if (mutation.type === 'attributes' && mutation.target instanceof Element) localizeElementAttributes(mutation.target, locale)
    })
  })
  observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: [...translatedAttributes] })
  return () => observer.disconnect()
}
